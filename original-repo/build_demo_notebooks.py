def make_revoke_nb():
    cells = [
        md("# 3) Revoke — revocation lifecycle\n\n"
           "Issue a diploma, revoke it, and show that a revoked document fails "
           "verification while the chain itself stays intact."),
        code(prelude()),
        code(
            "import shutil\n"
            "shutil.rmtree(CHAIN, ignore_errors=True)\n"
            "blockchain_util.init_block(CHAIN, 'UNIVERSITY-OF-UTOPIA-CHAIN')\n"
            "\n"
            "priv, pub = crypto_util.gen_dskey('ML_DSA_87')\n"
            "ds_algo = 'ML_DSA_87'\n"
            "blockchain_util.register_signer(CHAIN, 'UNIVERSITY OF UTOPIA', pub, ds_algo)\n"
            "\n"
            "DOC_DIPLOMA = " + json.dumps(DOC_DIPLOMA, ensure_ascii=False, indent=4) + "\n"
            "payload = blockchain_util.issue_payload(DOC_DIPLOMA)\n"
            "blockchain_util.append_block(CHAIN, payload, [(ds_algo, priv)])\n"
            "h_doc = payload['HashedDocument']\n"
            "print('issued. HashedDocument:', h_doc[:24] + '...')"
        ),
        code(
            "# 3a) Before revocation: issued, not revoked, VALID\n"
            "status = blockchain_util.fetch_status(CHAIN, h_doc)\n"
            "print('status:', status)\n"
            "result = blockchain_util.verify_document(CHAIN, DOC_DIPLOMA)\n"
            "blockchain_util.show_verdict(result)"
        ),
        code(
            "# 3b) Revoke the diploma\n"
            "blockchain_util.append_block(CHAIN, blockchain_util.revoke_payload(h_doc), [(ds_algo, priv)])\n"
            "status = blockchain_util.fetch_status(CHAIN, h_doc)\n"
            "print('status after revoke:', status)"
        ),
        code(
            "# 3c) After revocation: INVALID (not revoked check fails)\n"
            "result = blockchain_util.verify_document(CHAIN, DOC_DIPLOMA)\n"
            "blockchain_util.show_verdict(result)"
        ),
        code(
            "# 3d) The chain itself is still intact (revoke is a valid block)\n"
            "ok, report = blockchain_util.verify_chain(CHAIN)\n"
            "print('verify_chain:', ok, '| blocks:', len(report))\n"
            "print('blocks:', sorted(os.listdir(os.path.join(CHAIN, 'blocks'))))"
        ),
        code(
            "# 3e) A different (unrevoked) document remains VALID\n"
            "DOC_TRANSCRIPT = " + json.dumps(DOC_TRANSCRIPT, ensure_ascii=False, indent=4) + "\n"
            "blockchain_util.append_block(CHAIN, blockchain_util.issue_payload(DOC_TRANSCRIPT), [(ds_algo, priv)])\n"
            "result = blockchain_util.verify_document(CHAIN, DOC_TRANSCRIPT)\n"
            "blockchain_util.show_verdict(result)"
        ),
    ]
    return nbformat.v4.new_notebook(
        cells=cells,
        metadata={"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
    )


def build_all():
    notebooks = {
        "demo-issue.ipynb": make_issue_nb(),
        "demo-verify.ipynb": make_verify_nb(),
        "demo-revoke.ipynb": make_revoke_nb(),
    }
    for name, nb in notebooks.items():
        path = os.path.join(REPO, name)
        with open(path, "w", encoding="utf-8") as fh:
            nbformat.write(nb, fh)
        print("built", name)
    return notebooks


def execute_all(notebooks):
    for name, nb in notebooks.items():
        path = os.path.join(REPO, name)
        client = NotebookClient(nb, timeout=300, kernel_name="python3")
        client.execute()
        with open(path, "w", encoding="utf-8") as fh:
            nbformat.write(nb, fh)
        print("executed and saved", name)


def verify_execution():
    """Re-open the notebooks and count error outputs (used as a final check)."""
    problems = []
    for name in ("demo-issue.ipynb", "demo-verify.ipynb", "demo-revoke.ipynb"):
        with open(os.path.join(REPO, name), encoding="utf-8") as fh:
            nb = nbformat.read(fh, as_version=4)
        errors = 0
        for cell in nb.cells:
            for out in cell.get("outputs", []):
                if out.get("output_type") == "error":
                    errors += 1
                    problems.append((name, out.get("ename"), out.get("evalue")))
        print(f"{name}: cells={len(nb.cells)} error_outputs={errors}")
    return problems


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--execute", action="store_true", help="headless-execute after building")
    args = parser.parse_args()

    notebooks = build_all()
    if args.execute:
        execute_all(notebooks)
        problems = verify_execution()
        if problems:
            print("ERRORS FOUND:")
            for p in problems:
                print("  ", p)
            sys.exit(1)
        print("ALL NOTEBOOKS EXECUTED CLEANLY")
