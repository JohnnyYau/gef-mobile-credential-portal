class ChainTestCase(unittest.TestCase):
    def setUp(self):
        self._td = tempfile.mkdtemp(prefix="gef26-test-")
        self.chain = os.path.join(self._td, "demo-chain")
        blockchain_util.init_block(self.chain, "TestChain")
        self.priv, self.pub = crypto_util.gen_dskey("RSA-2048")
        self.algo = "RSA-2048"
        blockchain_util.register_signer(self.chain, "UNIVERSITY OF UTOPIA", self.pub, self.algo)

    def tearDown(self):
        shutil.rmtree(self._td, ignore_errors=True)

    def issue(self, doc=DIPLOMA, signers=None):
        payload = blockchain_util.issue_payload(doc)
        block = blockchain_util.append_block(
            self.chain, payload, signers or [(self.algo, self.priv)]
        )
        return payload, block

    def revoke(self, hashed_document, signers=None):
        payload = blockchain_util.revoke_payload(hashed_document)
        return blockchain_util.append_block(
            self.chain, payload, signers or [(self.algo, self.priv)]
        )


class TestInit(ChainTestCase):
    def test_genesis_fields(self):
        genesis = blockchain_util.load_block(self.chain, 0)
        self.assertEqual(genesis["height"], 0)
        self.assertEqual(genesis["prevHashSum"], "")
        self.assertEqual(genesis["timestamp"], 0)
        self.assertEqual(genesis["contentHashAlgo"], "sha3_512")
        self.assertEqual(genesis["payload"]["action"], "GENESIS")

    def test_deterministic_genesis(self):
        other = os.path.join(self._td, "other-chain")
        blockchain_util.init_block(other, "TestChain")
        self.assertEqual(
            crypto_util.hash_json(blockchain_util.load_block(self.chain, 0)),
            crypto_util.hash_json(blockchain_util.load_block(other, 0)),
        )

    def test_double_init_raises(self):
        with self.assertRaises(FileExistsError):
            blockchain_util.init_block(self.chain, "TestChain")

    def test_zero_padded_block_files(self):
        self.assertTrue(os.path.exists(
            os.path.join(self.chain, "blocks", "block-000000000.json")))


class TestAppend(ChainTestCase):
    def test_height_and_link(self):
        payload, block = self.issue()
        self.assertEqual(block["height"], 1)
        prev = blockchain_util.load_block(self.chain, 0)
        self.assertEqual(block["prevHashSum"], crypto_util.hash_json(prev))
        self.assertGreater(block["timestamp"], 0)

    def test_append_requires_signer(self):
        with self.assertRaises(ValueError):
            blockchain_util.append_block(self.chain, {"action": "ISSUE"}, [])

    def test_multi_signer_block(self):
        priv2, pub2 = crypto_util.gen_dskey("ec.SECP384R1")
        blockchain_util.register_signer(self.chain, "REGISTRY OFFICE", pub2, "ec.SECP384R1")
        payload = blockchain_util.issue_payload(DIPLOMA)
        block = blockchain_util.append_block(
            self.chain, payload, [("RSA-2048", self.priv), ("ec.SECP384R1", priv2)]
        )
        self.assertEqual(len(block["DataSignatureInfo"]), 2)
        ok, report = blockchain_util.verify_chain(self.chain)
        self.assertTrue(ok)

    def test_atomic_write_no_temp_residue(self):
        self.issue()
        residue = [f for f in os.listdir(os.path.join(self.chain, "blocks"))
                   if f.endswith(".temp")]
        self.assertEqual(residue, [])

    def test_last_height_tracking(self):
        self.assertEqual(blockchain_util.last_height(self.chain), 0)
        self.issue()
        self.issue()
        self.assertEqual(blockchain_util.last_height(self.chain), 2)


class TestVerifyChain(ChainTestCase):
    def test_clean_chain(self):
        self.issue()
        self.issue(TRANSCRIPT)
        self.revoke(blockchain_util.issue_payload(DIPLOMA)["HashedDocument"])
        ok, report = blockchain_util.verify_chain(self.chain)
        self.assertTrue(ok)
        self.assertEqual(len(report), 4)  # genesis + 3

    def test_tampered_middle_block_detected(self):
        self.issue(DIPLOMA)   # block 1
        self.issue(TRANSCRIPT)  # block 2
        # tamper the MIDDLE block (block 1) payload
        block_path = os.path.join(self.chain, "blocks", "block-000000001.json")
        with open(block_path, encoding="utf-8") as fh:
            block = json.load(fh)
        block["payload"]["HashedDocument"] = "tampered-hash"
        with open(block_path, "w", encoding="utf-8") as fh:
            json.dump(block, fh, ensure_ascii=False, indent=2)
        ok, report = blockchain_util.verify_chain(self.chain)
        self.assertFalse(ok)
        # block 1 itself no longer verifies (signature breaks),
        self.assertFalse(report[1]["ok"])
        # and block 2's prevHashSum no longer matches block 1's new hash
        self.assertFalse(report[2]["checks"]["prev_link"])

    def test_missing_block_detected(self):
        self.issue()
        self.issue()
        os.remove(os.path.join(self.chain, "blocks", "block-000000001.json"))
        ok, report = blockchain_util.verify_chain(self.chain)
        self.assertFalse(ok)
        self.assertFalse(report[1]["exists"])

    def test_reordered_blocks_detected(self):
        self.issue(TRANSCRIPT)  # block 1
        self.issue(DIPLOMA)     # block 2
        b1 = os.path.join(self.chain, "blocks", "block-000000001.json")
        b2 = os.path.join(self.chain, "blocks", "block-000000002.json")
        tmp = b1 + ".swap"
        os.replace(b1, tmp)
        os.replace(b2, b1)
        os.replace(tmp, b2)
        ok, _ = blockchain_util.verify_chain(self.chain)
        self.assertFalse(ok)

    def test_fetch_block_returns_none_for_broken(self):
        self.issue()
        self.assertIsNotNone(blockchain_util.fetch_block(self.chain, 1))
        block_path = os.path.join(self.chain, "blocks", "block-000000001.json")
        with open(block_path, encoding="utf-8") as fh:
            block = json.load(fh)
        block["payload"]["HashedDocumentInfo"] = "broken"
        with open(block_path, "w", encoding="utf-8") as fh:
            json.dump(block, fh, ensure_ascii=False, indent=2)
        self.assertIsNone(blockchain_util.fetch_block(self.chain, 1))


class TestVerifyDocument(ChainTestCase):
    def test_genuine_diploma_valid(self):
        payload, _ = self.issue(DIPLOMA)
        result = blockchain_util.verify_document(self.chain, DIPLOMA)
        self.assertTrue(result["valid"])
        self.assertEqual(result["hashed_document"], payload["HashedDocument"])
        for check in ("chain_integrity", "signer_trusted", "on_chain_record",
                      "hash_match", "signature_valid", "not_revoked"):
            self.assertTrue(result[check], check)

    def test_transcript_valid(self):
        self.issue(TRANSCRIPT)
        result = blockchain_util.verify_document(self.chain, TRANSCRIPT)
        self.assertTrue(result["valid"])

    def test_tampered_document_detected(self):
        self.issue(DIPLOMA)
        forged = json.loads(json.dumps(DIPLOMA))
        forged["AcademicInfo"]["DegreeName"] = "MSc Computer Science"
        result = blockchain_util.verify_document(self.chain, forged)
        self.assertFalse(result["valid"])
        self.assertFalse(result["hash_match"])

    def test_never_issued_document(self):
        other = json.loads(json.dumps(DIPLOMA))
        other["PersonalParticulars"]["StudentID"] = "99999999"
        result = blockchain_util.verify_document(self.chain, other)
        self.assertFalse(result["valid"])
        self.assertFalse(result["on_chain_record"])

    def test_unknown_signer_not_trusted(self):
        rogue, rogue_pub = crypto_util.gen_dskey("RSA-2048")
        payload = blockchain_util.issue_payload(DIPLOMA)
        blockchain_util.append_block(self.chain, payload, [("RSA-2048", rogue)])
        result = blockchain_util.verify_document(self.chain, DIPLOMA)
        self.assertFalse(result["valid"])
        self.assertFalse(result["signer_trusted"])
        self.assertFalse(result["signature_valid"])

    def test_revoked_document_invalid(self):
        payload, _ = self.issue(DIPLOMA)
        self.assertTrue(blockchain_util.verify_document(self.chain, DIPLOMA)["valid"])
        self.revoke(payload["HashedDocument"])
        result = blockchain_util.verify_document(self.chain, DIPLOMA)
        self.assertFalse(result["valid"])
        self.assertFalse(result["not_revoked"])


class TestStatus(ChainTestCase):
    def test_status_unknown_doc(self):
        status = blockchain_util.fetch_status(self.chain, "never-issued-hash")
        self.assertEqual(status, {"issued": False, "revoked": False,
                                  "issue_heights": [], "revoke_heights": []})

    def test_status_lifecycle(self):
        payload, _ = self.issue(DIPLOMA)
        h = payload["HashedDocument"]
        status = blockchain_util.fetch_status(self.chain, h)
        self.assertTrue(status["issued"])
        self.assertFalse(status["revoked"])
        self.assertEqual(status["issue_heights"], [1])
        self.revoke(h)
        status = blockchain_util.fetch_status(self.chain, h)
        self.assertTrue(status["revoked"])
        self.assertEqual(status["revoke_heights"], [2])

    def test_revoke_then_issue_then_revoke(self):
        payload, _ = self.issue(DIPLOMA)
        h = payload["HashedDocument"]
        self.revoke(h)
        self.issue(DIPLOMA)  # re-issue after revoke
        self.revoke(h)
        status = blockchain_util.fetch_status(self.chain, h)
        self.assertEqual(status["issue_heights"], [1, 3])
        self.assertEqual(status["revoke_heights"], [2, 4])
        # latest state wins: still revoked
        self.assertFalse(blockchain_util.verify_document(self.chain, DIPLOMA)["valid"])


class TestRegistry(ChainTestCase):
    def test_registry_persisted_in_info(self):
        info = blockchain_util.read_info(self.chain)
        self.assertEqual(len(info["trusted_signers"]), 1)
        signer = info["trusted_signers"][0]
        self.assertEqual(signer["name"], "UNIVERSITY OF UTOPIA")
        self.assertEqual(signer["ds_algo"], "RSA-2048")
        sha1, sha256 = crypto_util.getfgpt(self.pub)
        self.assertEqual(signer["sha1fgpt"], sha1)
        self.assertEqual(signer["sha256fgpt"], sha256)

    def test_register_same_key_dedups(self):
        blockchain_util.register_signer(self.chain, "AGAIN", self.pub, "RSA-2048")
        self.assertEqual(len(blockchain_util.trusted_signers(self.chain)), 1)

    def test_is_trusted(self):
        _, sha256 = crypto_util.getfgpt(self.pub)
        self.assertTrue(blockchain_util.is_trusted(self.chain, sha256))
        self.assertFalse(blockchain_util.is_trusted(self.chain, "00:00:00:00"))

    def test_signer_public_key_persisted(self):
        _, sha256 = crypto_util.getfgpt(self.pub)
        key_dir = os.path.join(self.chain, "keys")
        self.assertTrue(os.path.isdir(key_dir))
        self.assertEqual(len(os.listdir(key_dir)), 1)
        # the persisted key verifies a signature made by the registered private key
        nonce, sig = crypto_util.sign_json({"action": "ISSUE"}, "RSA-2048", self.priv)
        loaded = crypto_util.fetch_pubkey(os.path.join(key_dir, os.listdir(key_dir)[0]))
        self.assertTrue(crypto_util.verify_ds({"action": "ISSUE"}, "RSA-2048",
                                              loaded, sig, nonce))


