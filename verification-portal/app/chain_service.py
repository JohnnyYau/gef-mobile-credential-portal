def _info_path() -> str:
    return str(CHAIN_DIR / "info.yaml")


def _signer_priv_path(sha256fgpt: str):
    safe = sha256fgpt.replace(":", "")[:24]
    return CHAIN_DIR / "keys" / f"signer-{safe}.priv.pem"


def _ensure_signer() -> None:
    """Register the portal's data signer if the registry is empty."""
    if blockchain_util.trusted_signers(str(CHAIN_DIR)):
        return
    algo = SIGNER_ALGO
    priv, pub = crypto_util.gen_dskey(algo)
    _, sha256 = crypto_util.getfgpt(pub)
    key_dir = CHAIN_DIR / "keys"
    key_dir.mkdir(parents=True, exist_ok=True)
    crypto_util.save_privkey(priv, algo, str(_signer_priv_path(sha256)), None)
    blockchain_util.register_signer(str(CHAIN_DIR), SIGNER_NAME, pub, algo)


def _load_signer():
    """Return (ds_algo, private_key) of the active signer (or the first
    registered signer when none is explicitly activated)."""
    signers = blockchain_util.trusted_signers(str(CHAIN_DIR))
    if not signers:
        raise RuntimeError("No trusted signer is registered on this chain.")
    active = _active_signer_fgpt()
    chosen = next((s for s in signers if s["sha256fgpt"] == active), None)
    if chosen is None:
        chosen = signers[0]
    priv_path = _signer_priv_path(chosen["sha256fgpt"])
    if not priv_path.exists():
        raise RuntimeError(
            "Signer private key not found. The demo chain keeps keys under "
            "keys/signer-*.priv.pem; restore the key or delete the chain "
            "directory to re-seed."
        )
    priv = crypto_util.fetch_privkey(str(priv_path), None)
    return chosen["ds_algo"], priv


def _active_signer_fgpt():
    """Portal-side preference for which signer issues blocks."""
    try:
        path = CHAIN_DIR / "active-signer.json"
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8")).get("sha256fgpt")
    except (OSError, ValueError):
        pass
    return None


def _store_raw_document(document: dict, hashed_document: str) -> None:
    """Keep the full credential JSON under rawjsondocs/<hash>.json so the
    RAG index can retrieve readable text, not just hashes."""
    raw_dir = CHAIN_DIR / "rawjsondocs"
    raw_dir.mkdir(parents=True, exist_ok=True)
    with open(raw_dir / f"{hashed_document}.json", "w", encoding="utf-8") as fh:
        json.dump(document, fh, ensure_ascii=False, indent=2)


def _seed_samples() -> None:
    algo, priv = _load_signer()
    for doc in (SAMPLE_DIPLOMA, SAMPLE_TRANSCRIPT):
        payload = blockchain_util.issue_payload(doc)
        blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
        _store_raw_document(doc, payload["HashedDocument"])


def ensure_revoked_sample() -> str:
    """Public-mode landing sample: a credential that is issued AND revoked on
    the chain, exactly once. Idempotent across calls, restarts and instances
    sharing CHAIN_DIR; returns its on-chain hash."""
    ensure_chain()
    hashed = blockchain_util.issue_payload(SAMPLE_REVOKED_DOC)["HashedDocument"]
    with _lock:
        lifecycle = blockchain_util.fetch_status(str(CHAIN_DIR), hashed)
        if not lifecycle.get("issue_heights"):
            algo, priv = _load_signer()
            payload = blockchain_util.issue_payload(SAMPLE_REVOKED_DOC)
            blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
            _store_raw_document(SAMPLE_REVOKED_DOC, hashed)
        lifecycle = blockchain_util.fetch_status(str(CHAIN_DIR), hashed)
        if not lifecycle.get("revoke_heights"):
            algo, priv = _load_signer()
            payload = blockchain_util.revoke_payload(hashed)
            blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
    return hashed


def restore_snapshot_if_needed(url: str) -> bool:
    """Free-tier persistence hook: when the chain dir is empty and a snapshot
    URL is configured, fetch + restore a backup_chain.py export. Returns True
    when a snapshot was restored. Called from the app lifespan before
    ensure_chain(), which then sees existing info.yaml and skips re-seeding.

    Member paths are validated (no absolute paths, no '..') so a tampered
    snapshot cannot write outside the chain directory.
    """
    if os.path.exists(_info_path()):
        return False
    import io
    import tarfile
    import urllib.request

    try:
        with urllib.request.urlopen(url, timeout=60) as resp:
            data = resp.read()
    except Exception as exc:  # noqa: BLE001 — surface the restore failure loudly
        raise RuntimeError(f"CHAIN_SNAPSHOT_URL restore failed: {exc}") from exc
    CHAIN_DIR.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
        members = []
        for member in tf.getmembers():
            p = Path(member.name)
            if p.is_absolute() or ".." in p.parts:
                raise RuntimeError(
                    f"unsafe path in chain snapshot: {member.name!r}")
            members.append(member)
        tf.extractall(CHAIN_DIR, members=members)
    if not os.path.exists(_info_path()):
        raise RuntimeError("chain snapshot restored but info.yaml is missing")
    return True


def ensure_chain() -> None:
    """Initialise + seed the demo chain on first run (idempotent)."""
    with _lock:
        if not os.path.exists(_info_path()):
            blockchain_util.init_block(str(CHAIN_DIR), CHAIN_NAME)
            _ensure_signer()
            _seed_samples()
        else:
            _ensure_signer()  # chain exists but signer registry is empty


def chain_info() -> dict:
    ensure_chain()
    info = blockchain_util.read_info(str(CHAIN_DIR))
    return {
        "chain_name": info.get("chain_name"),
        "content_hash_algo": info.get("content_hash_algo"),
        "height": blockchain_util.last_height(str(CHAIN_DIR)),
        "signers": info.get("trusted_signers", []),
    }


def hash_of(document: dict) -> str:
    """On-chain hash of a full credential document."""
    return blockchain_util.issue_payload(document)["HashedDocument"]


def issue(document: dict) -> dict:
    ensure_chain()
    algo, priv = _load_signer()
    payload = blockchain_util.issue_payload(document)  # ValueError if sections missing
    with _lock:
        block = blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
        _store_raw_document(document, payload["HashedDocument"])
    return {
        "hashed_document": payload["HashedDocument"],
        "height": block["height"],
        "block": block,
    }


def revoke(hashed_document: str, reason: str | None = None,
           effective_at: float | None = None) -> dict:
    ensure_chain()
    algo, priv = _load_signer()
    payload = blockchain_util.revoke_payload(hashed_document)
    if reason:
        payload["reason"] = str(reason)[:200]
    if effective_at is not None:
        payload["effective_at"] = float(effective_at)
    with _lock:
        block = blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
    return {
        "hashed_document": hashed_document,
        "height": block["height"],
        "block": block,
    }


def revoked_records() -> list:
    """Per-hash latest REVOKE record (hash, height, reason, effective_at),
    sorted by hash — the source for the signed status list."""
    ensure_chain()
    chain = str(CHAIN_DIR)
    latest = {}
    for height in range(1, blockchain_util.last_height(chain) + 1):
        try:
            block = blockchain_util.load_block(chain, height)
        except blockchain_util.ChainDataError:
            continue
        payload = block.get("payload") or {}
        if payload.get("action") != "REVOKE":
            continue
        h = payload.get("HashedDocument")
        if h:
            latest[h] = {
                "hash": h,
                "height": height,
                "reason": payload.get("reason"),
                "effective_at": payload.get("effective_at"),
            }
    return sorted(latest.values(), key=lambda r: r["hash"])


def revoke_meta(hashed_document: str) -> dict:
    """Latest REVOKE metadata for one hash (reason / effective_at), if any."""
    for rec in revoked_records():
        if rec["hash"] == hashed_document:
            return rec
    return {}


def chain_snapshot_id() -> str:
    """'<height>:<hash of last block>' — changes only when the chain does."""
    ensure_chain()
    chain = str(CHAIN_DIR)
    height = blockchain_util.last_height(chain)
    try:
        last = blockchain_util.load_block(chain, height)
        return f"{height}:{crypto_util.hash_json(last, 'sha3_512')[:24]}"
    except Exception:  # noqa: BLE001 — corrupted tail still yields an id
        return f"{height}:corrupt"


def sign_payload(payload: dict):
    """Sign an arbitrary payload with the active signer.
    Returns (ds_algo, signature_b64) — the nonce is embedded in the payload."""
    algo, priv = _load_signer()
    _, signature = crypto_util.sign_json(payload, algo, priv)
    return algo, signature


def _corrupt_verdict(exc: Exception, hashed_document=None) -> dict:
    """Structured verdict when chain data is unreadable/corrupted."""
    return {
        "chain_integrity": False,
        "signer_trusted": False,
        "on_chain_record": None,
        "hash_match": None,
        "signature_valid": False,
        "not_revoked": None,
        "hashed_document": hashed_document,
        "valid": False,
        "verdict": "CHAIN DATA CORRUPT",
        "chain_error": str(exc),
    }


def status(hashed_document: str) -> dict:
    ensure_chain()
    return blockchain_util.fetch_status(str(CHAIN_DIR), hashed_document)


def verify_document(document: dict) -> dict:
    """Full six-check verification of a presented credential document."""
    for key in ("PersonalParticulars", "AcademicInfo", "DocumentInfo"):
        if key not in document:
            raise ValueError(f"Document missing required section: {key}")
    ensure_chain()
    try:
        result = blockchain_util.verify_document(str(CHAIN_DIR), document)
    except blockchain_util.ChainDataError as exc:
        return _corrupt_verdict(
            exc, blockchain_util.issue_payload(document)["HashedDocument"]
        )
    if result["valid"]:
        result["verdict"] = "VALID"
    elif not result["not_revoked"]:
        result["verdict"] = "REVOKED"
    else:
        result["verdict"] = "INVALID"
    return result


def verify_hash(hashed_document: str) -> dict:
    """Hash-level verification: every check that is computable without the
    full document. Check 4 (hash_match) requires the document, so it is
    reported as ``None`` with a note — upload the document for the full check.
    """
    ensure_chain()
    chain = str(CHAIN_DIR)

    try:
        chain_ok, _ = blockchain_util.verify_chain(chain)

        issue_block = issue_height = None
        for height in range(blockchain_util.last_height(chain), 0, -1):
            block = blockchain_util.load_block(chain, height)
            payload = block.get("payload", {})
            if (payload.get("action") == "ISSUE"
                    and payload.get("HashedDocument") == hashed_document):
                issue_block, issue_height = block, height
                break

        signer_trusted = signature_valid = False
        if issue_block is not None:
            fgpts = [d.get("DSsha256fgpt", "") for d in
                     issue_block.get("DataSignatureInfo", [])]
            signer_trusted = bool(fgpts) and all(
                blockchain_util.is_trusted(chain, f) for f in fgpts
            )
            signature_valid = blockchain_util.verify_block(chain, issue_height)["checks"].get(
                "signatures", False
            )

        lifecycle = blockchain_util.fetch_status(chain, hashed_document)
    except blockchain_util.ChainDataError as exc:
        return _corrupt_verdict(exc, hashed_document)

    result = {
        "chain_integrity": chain_ok,
        "signer_trusted": signer_trusted,
        "on_chain_record": issue_block is not None,
        "hash_match": None,  # requires the full document
        "signature_valid": signature_valid,
        "not_revoked": not lifecycle["revoked"],
        "hashed_document": hashed_document,
        "status": lifecycle,
    }
    if lifecycle["revoked"]:
        result["verdict"] = "REVOKED"
    elif issue_block is None:
        result["verdict"] = "NOT FOUND"
    elif chain_ok and signer_trusted and signature_valid:
        result["verdict"] = "VALID ON CHAIN"
    else:
        result["verdict"] = "INVALID"
    return result


