def list_signers() -> dict:
    """Registered signers + which one currently issues."""
    ensure_chain()
    signers = blockchain_util.trusted_signers(str(CHAIN_DIR))
    active = _active_signer_fgpt()
    if active is None and signers:
        active = signers[0]["sha256fgpt"]
    return {"signers": signers, "active": active}


def add_signer(name: str, ds_algo: str) -> dict:
    """Generate a fresh signer key, register it, and return its record."""
    ensure_chain()
    try:
        priv, pub = crypto_util.gen_dskey(ds_algo)
    except Exception as exc:  # noqa: BLE001 — bad algo name surfaces as 422
        raise ValueError(f"Unsupported ds_algo '{ds_algo}': {exc}") from exc
    _, sha256 = crypto_util.getfgpt(pub)
    key_dir = CHAIN_DIR / "keys"
    key_dir.mkdir(parents=True, exist_ok=True)
    crypto_util.save_privkey(priv, ds_algo, str(_signer_priv_path(sha256)), None)
    blockchain_util.register_signer(str(CHAIN_DIR), name, pub, ds_algo)
    record = next(s for s in blockchain_util.trusted_signers(str(CHAIN_DIR))
                  if s["sha256fgpt"] == sha256)
    record["active"] = (sha256 == _active_signer_fgpt())
    return record


def set_active_signer(sha256fgpt: str) -> dict:
    """Make the given registered signer the one that signs new blocks."""
    ensure_chain()
    signers = blockchain_util.trusted_signers(str(CHAIN_DIR))
    if not any(s["sha256fgpt"] == sha256fgpt for s in signers):
        raise ValueError("No registered signer has that fingerprint.")
    path = CHAIN_DIR / "active-signer.json"
    path.write_text(json.dumps({"sha256fgpt": sha256fgpt}), encoding="utf-8")
    return {"active": sha256fgpt}


def student_credentials(student_id: str, dob: str | None = None) -> dict:
    """Issuer-side student lookup.

    The chain itself stores only hashes — it deliberately keeps plaintext off
    the ledger. The portal keeps the raw documents under ``rawjsondocs/`` (for
    RAG + this registry), so the issuer can index by StudentID there without
    ever putting plaintext on the chain.
    """
    ensure_chain()
    raw_dir = CHAIN_DIR / "rawjsondocs"
    matches = []
    if raw_dir.exists():
        for f in sorted(raw_dir.glob("*.json")):
            try:
                doc = json.loads(f.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            pp = doc.get("PersonalParticulars") or {}
            if pp.get("StudentID") != student_id:
                continue
            if dob and pp.get("DOB") != dob:
                continue
            h = blockchain_util.issue_payload(doc)["HashedDocument"]
            status = blockchain_util.fetch_status(str(CHAIN_DIR), h)
            docinfo = doc.get("DocumentInfo") or {}
            ai = doc.get("AcademicInfo") or {}
            matches.append({
                "hashed_document": h,
                "doc_type": docinfo.get("DocType", "CREDENTIAL"),
                "degree": ai.get("DegreeName") or "—",
                "issued_height": status.get("issued_height"),
                "issued_at": status.get("issued_at"),
                "revoked": status.get("revoked", False),
                "verdict": "REVOKED" if status.get("revoked") else "VALID ON CHAIN",
            })
    return {"student_id": student_id, "credentials": matches}
