def _info_path() -> str:
    return str(CHAIN_DIR / "info.yaml")


def _signer_priv_path(sha256fgpt: str):
    safe = sha256fgpt.replace(":", "")[:24]
    return CHAIN_DIR / "keys" / f"signer-{safe}.priv.pem"


def _passphrase() -> str:
    """Passphrase for the signer key at rest (batch U10).

    Read from ``cfg`` at call time, not at import time, so a deployment can
    inject it after the module is loaded and tests can flip it per case.
    """
    return getattr(cfg, "SIGNER_KEY_PASSPHRASE", "") or ""


def _looks_encrypted(path) -> bool:
    """True when the PEM/DER key on disk is passphrase-protected.

    Detection reads the header rather than attempting a decrypt, so a wrong
    passphrase still reports "this key is encrypted" instead of "not encrypted".
    """
    try:
        head = Path(path).read_bytes()[:64]
    except OSError:
        return False
    return b"ENCRYPTED PRIVATE KEY" in head or b"Proc-Type: 4,ENCRYPTED" in head


def load_private_key(path, algo: str):
    """Load the signer private key, honouring ``GEF_KEY_PASSPHRASE``.

    Three cases, all deliberate:

    * passphrase set + key already encrypted  → decrypt with it;
    * passphrase set + key still plaintext    → decrypt with no password, then
      rewrite it encrypted in place (migration; the file's plaintext window
      ends at first load instead of never);
    * passphrase set + decryption fails       → raise, never silently generate
      a replacement key (a new key would orphan every block already signed).
    """
    passphrase = _passphrase()
    try:
        return crypto_util.fetch_privkey(str(path), passphrase or None)
    except TypeError:
        # "Password was given but private key is not encrypted"
        if not passphrase:
            raise
        private = crypto_util.fetch_privkey(str(path), None)
        crypto_util.save_privkey(private, algo, str(path), passphrase)
        blockchain_util.invalidate_caches(str(CHAIN_DIR))
        return private
    except ValueError as exc:
        if not passphrase:
            raise SignerUnavailableError(
                f"Signer private key at {path} could not be parsed: {exc}"
            ) from exc
        raise SignerUnavailableError(
            f"Signer private key at {path} could not be decrypted with "
            "GEF_KEY_PASSPHRASE — the passphrase does not match the key on "
            "disk. Restore the correct passphrase; this chain will not fall "
            "back to another key."
        ) from exc


def _ensure_signer() -> None:
    """Register the portal's data signer if the registry is empty."""
    if blockchain_util.trusted_signers(str(CHAIN_DIR)):
        return
    algo = SIGNER_ALGO
    priv, pub = crypto_util.gen_dskey(algo)
    _, sha256 = crypto_util.getfgpt(pub)
    key_dir = CHAIN_DIR / "keys"
    key_dir.mkdir(parents=True, exist_ok=True)
    crypto_util.save_privkey(priv, algo, str(_signer_priv_path(sha256)),
                             _passphrase() or None)
    blockchain_util.register_signer(str(CHAIN_DIR), SIGNER_NAME, pub, algo)


def _load_signer():
    """Return (ds_algo, private_key) of the active signer (or the first
    registered signer when none is explicitly activated)."""
    signers = blockchain_util.trusted_signers(str(CHAIN_DIR))
    if not signers:
        raise SignerUnavailableError(
            "No trusted signer is registered on this chain.")
    active = _active_signer_fgpt()
    chosen = next((s for s in signers if s["sha256fgpt"] == active), None)
    if chosen is None:
        chosen = signers[0]
    priv_path = _signer_priv_path(chosen["sha256fgpt"])
    if not priv_path.exists():
        raise SignerUnavailableError(
            "Signer private key not found. The demo chain keeps keys under "
            "keys/signer-*.priv.pem; restore the key or delete the chain "
            "directory to re-seed."
        )
    if _passphrase() and not _looks_encrypted(priv_path):
        logger.warning("signer key %s was stored unencrypted; re-encrypting it "
                       "with GEF_KEY_PASSPHRASE", priv_path.name)
    return chosen["ds_algo"], load_private_key(priv_path, chosen["ds_algo"])


def _active_signer_fgpt():
    """Portal-side preference for which signer issues blocks."""
    try:
        path = CHAIN_DIR / "active-signer.json"
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8")).get("sha256fgpt")
    except (OSError, ValueError):
        pass
    return None


def _store_holder_index(document: dict, hashed_document: str) -> None:
    """U12 R5: a PII-free row beside the raw document.

    The raw JSON stays the issuer's own copy (RAG, PDF rendering, disclosure),
    but the holder/student lookup does not need names, DOB or e-mail — so it
    reads this instead. That is what makes it safe to ship a bundle without
    ``rawjsondocs/``: the demo still resolves a credential by StudentID, while
    the bundle carries no plaintext identity data.

    One file per hash, written once: no read-modify-write race between
    concurrent issues.
    """
    index_dir = CHAIN_DIR / "holder_index"
    pp = document.get("PersonalParticulars") or {}
    docinfo = document.get("DocumentInfo") or {}
    ai = document.get("AcademicInfo") or {}
    row = {
        "sid": str(pp.get("StudentID") or ""),
        "hashed_document": hashed_document,
        "doc_type": docinfo.get("DocType") or "CREDENTIAL",
        "degree": ai.get("DegreeName") or "—",
    }
    try:
        index_dir.mkdir(parents=True, exist_ok=True)
        target = index_dir / f"{hashed_document}.json"
        tmp = target.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(row, ensure_ascii=False), encoding="utf-8")
        tmp.replace(target)
    except OSError as exc:
        # Same typed failure as the raw write: a full disk must be
        # distinguishable from corrupt chain data.
        raise FileAccessError(
            f"could not store the holder index row for "
            f"{hashed_document[:12]}...: {exc}"
        ) from exc


def _store_raw_document(document: dict, hashed_document: str) -> None:
    """Keep the full credential JSON under rawjsondocs/<hash>.json so the
    RAG index can retrieve readable text, not just hashes."""
    _store_holder_index(document, hashed_document)
    raw_dir = CHAIN_DIR / "rawjsondocs"
    try:
        raw_dir.mkdir(parents=True, exist_ok=True)
        with open(raw_dir / f"{hashed_document}.json", "w",
                  encoding="utf-8") as fh:
            json.dump(document, fh, ensure_ascii=False, indent=2)
    except OSError as exc:
        # U10: typed so a full disk / read-only chain dir is distinguishable
        # from "the chain data is corrupt" (ChainDataError).
        raise FileAccessError(
            f"could not store the raw document for {hashed_document[:12]}...: "
            f"{exc}"
        ) from exc


def _seed_samples() -> None:
    algo, priv = _load_signer()
    for doc in (SAMPLE_DIPLOMA, SAMPLE_TRANSCRIPT):
        payload = blockchain_util.issue_payload(doc)
        blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
        _store_raw_document(doc, payload["HashedDocument"])


def ensure_revoked_sample() -> str:
    """Public-mode landing sample: a credential that is issued AND revoked on
    the chain, exactly once. Idempotent across calls, restarts and instances
    sharing CHAIN_DIR; returns its on-chain hash."""
    ensure_chain()
    hashed = blockchain_util.issue_payload(SAMPLE_REVOKED_DOC)["HashedDocument"]
    with _lock:
        lifecycle = blockchain_util.fetch_status(str(CHAIN_DIR), hashed)
        if not lifecycle.get("issue_heights"):
            algo, priv = _load_signer()
            payload = blockchain_util.issue_payload(SAMPLE_REVOKED_DOC)
            blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
            _store_raw_document(SAMPLE_REVOKED_DOC, hashed)
        lifecycle = blockchain_util.fetch_status(str(CHAIN_DIR), hashed)
        if not lifecycle.get("revoke_heights"):
            algo, priv = _load_signer()
            payload = blockchain_util.revoke_payload(hashed)
            blockchain_util.append_block(str(CHAIN_DIR), payload, [(algo, priv)])
    return hashed


def restore_snapshot_if_needed(url: str) -> bool:
    """Free-tier persistence hook: when the chain dir is empty and a snapshot
    URL is configured, fetch + restore a backup_chain.py export. Returns True
    when a snapshot was restored. Called from the app lifespan before
    ensure_chain(), which then sees existing info.yaml and skips re-seeding.

    Members are validated by ``app.backup.safe_members`` — no absolute paths,
    no ``..``, and no symlinks / hardlinks / devices (a link inside a tarball
    is how an extraction escapes the target directory). When the snapshot
    carries a ``MANIFEST.json`` (U8.1 exports do), every file's SHA-256 is
    checked after extraction; a mismatch aborts the boot instead of serving a
    half-restored chain — a chain that cannot prove itself is worse than none.
    """
    if os.path.exists(_info_path()):
        return False

    try:
        with urllib.request.urlopen(url, timeout=CHAIN_SNAPSHOT_TIMEOUT) as resp:
            data = resp.read()
    except Exception as exc:  # noqa: BLE001 — surface the restore failure loudly
        raise RuntimeError(f"CHAIN_SNAPSHOT_URL restore failed: {exc}") from exc

    CHAIN_DIR.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
        backup.extract_safely(tf, CHAIN_DIR)
        manifest = backup.read_manifest(tf)
    if not os.path.exists(_info_path()):
        raise RuntimeError("chain snapshot restored but info.yaml is missing")
    if manifest is not None:
        problems = backup.audit_restored(Path(CHAIN_DIR), manifest, require_all=False)
        if problems:
            raise RuntimeError(
                "chain snapshot failed manifest verification: "
                + "; ".join(problems[:3]))
    return True


def ensure_chain() -> None:
    """Initialise + seed the demo chain on first run (idempotent)."""
    with _lock:
        if not os.path.exists(_info_path()):
            blockchain_util.init_block(str(CHAIN_DIR), CHAIN_NAME)
            _ensure_signer()
            _seed_samples()
        else:
            _ensure_signer()  # chain exists but signer registry is empty


def chain_info() -> dict:
    ensure_chain()
    info = blockchain_util.read_info(str(CHAIN_DIR))
    return {
        "chain_name": info.get("chain_name"),
        "content_hash_algo": info.get("content_hash_algo"),
        "height": blockchain_util.last_height(str(CHAIN_DIR)),
        "signers": info.get("trusted_signers", []),
    }
