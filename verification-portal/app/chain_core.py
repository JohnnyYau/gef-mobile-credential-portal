"""chain_core.py — shared chain infrastructure (internal, batch U1.2).

Owns the pieces every service module needs and only one of them may own:

* the process-wide ``_lock`` (a single reentrant lock; if each module made its
  own, seeding and issuing could race on the chain directory),
* chain-directory paths and the signer private-key location,
* signer key generation / loading,
* chain initialisation, demo-chain seeding, snapshot restore.

Dependency direction: this module imports only ``blockchain_util`` /
``crypto_util`` / ``config``. It must never import a ``*_service`` module, so
there is no cycle.
"""

