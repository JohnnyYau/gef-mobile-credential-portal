#!/usr/bin/env python3
"""license_audit.py — dependency licence inventory + SBOM (batch U8.3).

"Free and open source, no GPL-3.0" is a constraint, not a feeling: it needs a
list you can check. This script walks the installed distributions in the
active interpreter (the same venv that runs the tests), reads each package's
own metadata, classifies the licence, and writes:

    docs/SBOM.md         human-readable table, one row per distribution
    docs/SBOM.json       machine-readable (name, version, licence, verdict)

Verdicts:
    OK        permissive (MIT / BSD / Apache / ISC / PSF / Unlicense ...)
    NOTE      weak copyleft or ambiguous-but-permitted (MPL-2.0, dual-licence
              where one branch is permissive); allowed, must be annotated
    BLOCK     strong copyleft (GPL / AGPL) or proprietary — the batch fails on
              these, they may not be shipped
    UNKNOWN   no licence metadata; treated as BLOCK until a human resolves it

The tool only reads metadata. It never installs, upgrades or removes anything.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from importlib.metadata import distributions
from pathlib import Path

STRONG_COPYLEFT = ("GPL-3", "GPL-2", "AGPL", "GPLV3", "GPLV2", "GNU GENERAL PUBLIC")
WEAK_COPYLEFT = ("MPL-2", "MPL 2", "MOZILLA PUBLIC", "LGPL", "LESSER GENERAL")
PERMISSIVE = ("MIT", "BSD", "APACHE", "ISC", "PSF", "PYTHON SOFTWARE",
              "UNLICENSE", "CC0", "ZLIB", "BSL-1")

#: Interpreter-level packages that are not project dependencies but appear in
#: the venv (pip, setuptools, wheel). Listed separately in the report.
TOOLING = ("pip", "setuptools", "wheel", "pkg-resources")


def _licence_text(dist) -> str:
    """Best-effort licence string from wheel metadata (never raises)."""
    meta = dist.metadata
    parts = [
        meta.get("License-Expression") or "",
        meta.get("License") or "",
    ]
    for classifier in meta.get_all("Classifier") or []:
        if classifier.startswith("License ::"):
            parts.append(classifier.split("::")[-1])
    text = " | ".join(p.strip() for p in parts if p and p.strip())
    # some packages ship a whole licence preamble in License:
    if len(text) > 200:
        first_line = text.splitlines()[0]
        text = first_line[:200]
    return text or "UNKNOWN"


def classify(licence: str) -> str:
    upper = licence.upper()
    if "UNKNOWN" in upper or not licence.strip():
        return "UNKNOWN"
    # dual licensed: "MIT OR GPL-3.0" — the permissive branch is what we use
    if re.search(r"\bOR\b", upper) and any(p in upper for p in PERMISSIVE):
        return "NOTE"
    if any(token in upper for token in STRONG_COPYLEFT):
        return "BLOCK"
    if any(token in upper for token in WEAK_COPYLEFT):
        return "NOTE"
    if any(token in upper for token in PERMISSIVE):
        return "OK"
    return "UNKNOWN"


def installed_packages() -> list[dict[str, str]]:
    rows = []
    for dist in distributions():
        name = dist.metadata["Name"] or dist.name or "?"
        version = dist.version or "?"
        licence = _licence_text(dist)
        rows.append({"name": name, "version": version, "license": licence,
                     "verdict": classify(licence)})
    return sorted(rows, key=lambda r: r["name"].lower())


def direct_dependencies(lock_path: Path) -> set[str]:
    names = set()
    if not lock_path.is_file():
        return names
    for line in lock_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name = re.split(r"[=<>\[; ]", line, maxsplit=1)[0]
        names.add(name.lower().replace("_", "-"))
    return names


def render_markdown(rows: list[dict[str, str]], direct: set[str]) -> str:
    counts = {v: sum(1 for r in rows if r["verdict"] == v)
              for v in ("OK", "NOTE", "BLOCK", "UNKNOWN")}
    lines = [
        "# Dependency licence inventory (batch U8.3)",
        "",
        "Generated by `scripts/license_audit.py` from the metadata of the "
        "installed distributions in this venv. Regenerate after any dependency "
        "change.",
        "",
        f"- distributions scanned: **{len(rows)}**",
        f"- OK (permissive): **{counts['OK']}** · NOTE (weak copyleft / dual): "
        f"**{counts['NOTE']}** · BLOCK (strong copyleft or proprietary): "
        f"**{counts['BLOCK']}** · UNKNOWN: **{counts['UNKNOWN']}**",
        "",
        "Policy: MIT / BSD / Apache / ISC / PSF are accepted. MPL-2.0 and LGPL "
        "are accepted **with annotation** (weak copyleft: unmodified library "
        "use only, no static linking into our source). GPL / AGPL are not "
        "shipped. UNKNOWN is treated as BLOCK until resolved.",
        "",
        "| Package | Version | Licence | Verdict | Direct? |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        mark = {"OK": "OK", "NOTE": "NOTE", "BLOCK": "**BLOCK**",
                "UNKNOWN": "**UNKNOWN**"}[row["verdict"]]
        flag = "direct" if row["name"].lower().replace("_", "-") in direct else ""
        licence = row["license"].replace("|", "/")
        if len(licence) > 90:
            licence = licence[:87] + "..."
        lines.append(f"| {row['name']} | {row['version']} | {licence} | "
                     f"{mark} | {flag} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default="docs")
    parser.add_argument("--lock", default="requirements-lock.txt")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any BLOCK/UNKNOWN exists (CI gate)")
    args = parser.parse_args()

    root = Path(__file__).resolve().parent.parent
    out_dir = (root / args.out_dir)
    direct = direct_dependencies(root / args.lock)
    rows = installed_packages()
    project_rows = [r for r in rows
                    if r["name"].lower() not in TOOLING]

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "SBOM.md").write_text(
        render_markdown(project_rows, direct), encoding="utf-8")
    (out_dir / "SBOM.json").write_text(json.dumps({
        "generated_from": "importlib.metadata",
        "python": sys.version.split()[0],
        "policy": {"accepted": ["MIT", "BSD", "Apache", "ISC", "PSF"],
                   "annotated": ["MPL-2.0", "LGPL"],
                   "rejected": ["GPL", "AGPL", "proprietary"]},
        "distributions": project_rows,
    }, indent=2) + "\n", encoding="utf-8")

    blocked = [r for r in project_rows if r["verdict"] in ("BLOCK", "UNKNOWN")]
    noted = [r for r in project_rows if r["verdict"] == "NOTE"]
    print(f"scanned {len(project_rows)} distributions -> {out_dir / 'SBOM.md'}")
    print(f"  OK {sum(1 for r in project_rows if r['verdict'] == 'OK')} | "
          f"NOTE {len(noted)} | BLOCK/UNKNOWN {len(blocked)}")
    for row in noted:
        print(f"  NOTE  {row['name']} {row['version']}: {row['license'][:70]}")
    for row in blocked:
        print(f"  BLOCK {row['name']} {row['version']}: {row['license'][:70]}",
              file=sys.stderr)
    if args.check and blocked:
        print("error: rejected licences present — see docs/SBOM.md", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
